// 根据默认名称列表生成带标识、默认标记和创建时间的食物对象。
export const createDefaultFoods = (): Food[] => {
  const now = Date.now();
  return DEFAULT_FOOD_NAMES.map((name, index) => ({
    id: `default-${index}-${now}`,
    name,
    isDefault: true,
    createdAt: now - (DEFAULT_FOOD_NAMES.length - index),
  }) /* 将默认名称及其序号转换为一个默认食物对象。 */);
};
